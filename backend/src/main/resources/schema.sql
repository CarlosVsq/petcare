DROP TABLE IF EXISTS tratamientos;
DROP TABLE IF EXISTS atenciones;
DROP TABLE IF EXISTS reservas;
DROP TABLE IF EXISTS horarios_veterinario;
DROP TABLE IF EXISTS veterinarios;
DROP TABLE IF EXISTS mascotas;
DROP TABLE IF EXISTS clientes;

CREATE TABLE clientes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut       VARCHAR(12)  NOT NULL UNIQUE,
    nombre    VARCHAR(150) NOT NULL,
    correo    VARCHAR(150) NOT NULL,
    telefono  VARCHAR(20),
    direccion VARCHAR(200)
);

CREATE TABLE mascotas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       BIGINT       NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
    nombre           VARCHAR(80)  NOT NULL,
    especie          VARCHAR(50)  NOT NULL,
    raza             VARCHAR(80),
    fecha_nacimiento DATE         NOT NULL,
    peso             NUMERIC(5,2) NOT NULL CHECK (peso > 0)
);

CREATE TABLE veterinarios (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL,
    especialidad VARCHAR(100) NOT NULL,
    correo       VARCHAR(150) NOT NULL
);

CREATE TABLE horarios_veterinario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veterinario_id BIGINT      NOT NULL REFERENCES veterinarios (id) ON DELETE CASCADE,
    dia_semana     VARCHAR(10) NOT NULL,
    hora_inicio    TIME        NOT NULL,
    hora_fin       TIME        NOT NULL,
    CHECK (hora_fin > hora_inicio)
);

CREATE TABLE reservas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id     BIGINT       NOT NULL REFERENCES mascotas (id),
    veterinario_id BIGINT       NOT NULL REFERENCES veterinarios (id),
    fecha          DATE         NOT NULL,
    hora           TIME         NOT NULL,
    motivo         VARCHAR(255) NOT NULL,
    estado         VARCHAR(20)  NOT NULL
);

CREATE UNIQUE INDEX uq_reserva_veterinario_horario
    ON reservas (veterinario_id, fecha, hora)
    WHERE estado <> 'CANCELADA';

CREATE TABLE atenciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id    BIGINT       NOT NULL UNIQUE REFERENCES reservas (id),
    diagnostico   VARCHAR(500) NOT NULL,
    observaciones VARCHAR(500)
);

CREATE TABLE tratamientos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atencion_id BIGINT       NOT NULL REFERENCES atenciones (id) ON DELETE CASCADE,
    medicamento VARCHAR(150) NOT NULL,
    dosis       VARCHAR(100) NOT NULL,
    frecuencia  VARCHAR(100) NOT NULL,
    duracion    VARCHAR(100) NOT NULL
);
